#!/usr/bin/env python3
"""Generate src/bugcodes.c from bsodrev/tables/bugcheck_names.json.

Source of the table: ntoskrnl.exe RT_MESSAGETABLE (Type 11, Name ID 1),
loaded by InitBootProcessor into KiBugCodeMessages and read back by
KeGetBugMessageText. The kernel walks {LoId, HighId, Offset} range blocks and
steps packed string entries; KeGetBugMessageText returns NULL for a miss and
KiDisplayBlueScreen then formats the code with "0x%08x".

Entries kept in the shipped table are the real bugcheck/verifier/livedump
codes. Dropped: SAVER_* (screen saver / shell diagnostics), XBOX_*, format
templates with %/%hs placeholders, and the 0x40000xxx console/version strings
that never appear on a bugcheck screen.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_PATH = os.path.join(ROOT, "tables", "bugcheck_names.json")
OUT_PATH = os.path.join(ROOT, "..", "src", "bugcodes.c")


def keep(code: int, name: str) -> bool:
    if code >= 0x40000000:
        return False
    if name.startswith("SAVER_") or name.startswith("XBOX_"):
        return False
    if any(ch in name for ch in "%[]()"):
        return False
    return True


def main() -> int:
    data = json.load(open(JSON_PATH, encoding="utf-8"))
    rows = []
    for k, v in data.items():
        code = int(k, 16)
        if keep(code, v):
            rows.append((code, v))
    rows.sort()

    lines = []
    lines.append("/* Generated by bsodrev/scripts/gen_bugcodes.py — do not edit by hand.")
    lines.append(" * bugcheck code -> friendly name, reverse engineered from the")
    lines.append(" * ntoskrnl.exe RT_MESSAGETABLE (Type 11, ID 1) read by KeGetBugMessageText.")
    lines.append(" * Regenerate after refreshing tables/bugcheck_names.json.")
    lines.append(" */")
    lines.append('#include "bugcodes.h"')
    lines.append("")
    lines.append("const BugCode g_bugcodes[] = {")
    for code, name in rows:
        lines.append('    { 0x%08Xu, "%s" },' % (code, name))
    lines.append("};")
    lines.append("")
    lines.append("const int g_bugcode_count = (int)(sizeof(g_bugcodes) / sizeof(g_bugcodes[0]));")
    lines.append("")
    lines.append("const char *bugcode_lookup(uint32_t code) {")
    lines.append("    int i;")
    lines.append("    for (i = 0; i < g_bugcode_count; i++)")
    lines.append("        if (g_bugcodes[i].code == code) return g_bugcodes[i].name;")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")

    out = os.path.normpath(OUT_PATH)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d entries)" % (out, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
